def rows() -> list[dict]:
    with CSV.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def kpi(hours: int) -> dict:
    """The chiller_kpi tool's arithmetic (common/alto_ops/src/alto_ops/chiller_tool.py): the last hours*4 rows."""
    rs = rows()[-max(1, int(hours)) * 4:]
    kw = sum(float(r["kw"]) for r in rs) / len(rs)
    rt = sum(float(r["rt"]) for r in rs) / len(rs)
    eff = kw / rt
    return {"hours": hours, "avg_kw": round(kw, 1), "avg_rt": round(rt, 1), "kw_per_rt": round(eff, 3),
            "status": "ALARM" if eff > ALARM else "OK", "rows": len(rs)}


