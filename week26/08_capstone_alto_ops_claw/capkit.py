        ("What is the plant kW/RT over the last 24 hours?", eff(24)),
        ("What is the plant kW/RT over the last hour?", eff(1)),
        ("What is the plant kW/RT over the last 2 hours?", eff(2)),
        ("What is the plant kW/RT over the last 3 hours?", eff(3)),
        ("What is the plant kW/RT over the last 4 hours?", eff(4)),
        ("What is the plant kW/RT over the last 8 hours?", eff(8)),
        ("What is the plant kW/RT over the last 12 hours?", eff(12)),
        ("What is the plant kW/RT over the last 48 hours?", eff(48)),
        ("What is the plant kW/RT over the last 72 hours?", eff(72)),
        ("What is the plant kW/RT over the whole last week (168 hours)?", eff(168)),
        ("What was the average plant power in kW over the last 6 hours?", f"{k[6]['avg_kw']:.1f} kW"),
        ("What was the average cooling load in RT over the last 6 hours?", f"{k[6]['avg_rt']:.1f} RT"),
        ("What was the average plant power in kW over the last 24 hours?", f"{k[24]['avg_kw']:.1f} kW"),
        ("What was the average cooling load in RT over the last 24 hours?", f"{k[24]['avg_rt']:.1f} RT"),
